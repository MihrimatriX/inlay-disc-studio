// Generates AOT-safe [GeneratedComInterface] bindings for the WebView2 interfaces the launcher uses, straight from
// the SDK's WebView2.h so vtable order can never drift. Usage: node scripts/gen-webview2.mjs <path-to-WebView2.h>
import { readFileSync, writeFileSync } from "node:fs";

const wanted = [
  "ICoreWebView2Environment",
  "ICoreWebView2Controller", "ICoreWebView2Controller2",
  "ICoreWebView2", "ICoreWebView2_2", "ICoreWebView2_3",
  "ICoreWebView2Settings",
  "ICoreWebView2NavigationStartingEventArgs",
  "ICoreWebView2NavigationCompletedEventArgs",
  "ICoreWebView2WebMessageReceivedEventArgs",
  "ICoreWebView2NewWindowRequestedEventArgs",
  "ICoreWebView2WebResourceRequestedEventArgs",
  "ICoreWebView2WebResourceRequest",
  "ICoreWebView2WebResourceResponse",
  "ICoreWebView2CreateCoreWebView2EnvironmentCompletedHandler",
  "ICoreWebView2CreateCoreWebView2ControllerCompletedHandler",
  "ICoreWebView2NavigationStartingEventHandler",
  "ICoreWebView2NavigationCompletedEventHandler",
  "ICoreWebView2WebMessageReceivedEventHandler",
  "ICoreWebView2NewWindowRequestedEventHandler",
  "ICoreWebView2WebResourceRequestedEventHandler",
  "ICoreWebView2ContainsFullScreenElementChangedEventHandler",
];

const header = readFileSync(process.argv[2], "utf8").replaceAll("\r\n", "\n");
const set = new Set(wanted);

/** @param {string} name */
function parse(name) {
  const m = header.match(new RegExp(`MIDL_INTERFACE\\("([0-9A-Fa-f-]+)"\\)\\s*${name}\\s*:\\s*public\\s+(\\w+)\\s*\\{([\\s\\S]*?)\\n    \\};`));
  if (!m) throw new Error(`${name} not found`);
  const [, iid, base, body] = m;
  const methods = [...body.matchAll(/virtual[^;]*?STDMETHODCALLTYPE\s+(\w+)\(([\s\S]*?)\)\s*=\s*0;/g)].map(x => ({
    name: x[1],
    params: x[2].replace(/\/\*.*?\*\//g, "").replace(/\s+/g, " ").trim(),
  }));
  return { iid, base, methods };
}

/** @type {Record<string, string>} */
const scalars = { HRESULT: "int", BOOL: "int", int: "int", UINT32: "uint", INT32: "int", UINT64: "ulong", INT64: "long", double: "double", HWND: "nint", RECT: "RECT", COREWEBVIEW2_COLOR: "COREWEBVIEW2_COLOR", EventRegistrationToken: "long" };

/** @param {string} p @param {number} i */
function mapParam(p, i) {
  const m = p.match(/^(?:const\s+)?(\w+)\s*(\*{0,2})\s*(\w+)$/);
  if (!m) throw new Error(`cannot parse param "${p}"`);
  const [, type, stars, pname] = m;
  const id = pname === "object" || pname === "event" || pname === "string" ? `@${pname}` : pname;
  const out = (/** @type {string} */ t) => `out ${t} ${id}`;
  if (type === "LPCWSTR") return `string ${id}`;
  if (type === "LPWSTR" && stars === "*") return out("string");
  const scalar = scalars[type] ?? (type.startsWith("COREWEBVIEW2_") ? "int" : null);
  if (scalar) return stars ? out(scalar) : `${scalar} ${id}`;
  if (/^I\w+$/.test(type)) {
    const t = set.has(type) ? `${type}?` : "nint";
    if (stars === "*") return `${t} ${id}`;
    if (stars === "**") return out(t);
  }
  throw new Error(`unmapped type "${p}" (#${i})`);
}

let out = `// <auto-generated> by scripts/gen-webview2.mjs from WebView2.h. Do not edit. </auto-generated>
#nullable enable
#pragma warning disable IDE1006, CS1591
using System.Runtime.InteropServices;
using System.Runtime.InteropServices.Marshalling;

namespace Inlay.Launcher.WebView2;

[StructLayout(LayoutKind.Sequential)] public struct RECT { public int Left, Top, Right, Bottom; }
[StructLayout(LayoutKind.Sequential)] public struct COREWEBVIEW2_COLOR { public byte A, R, G, B; }
`;
for (const name of wanted) {
  const { iid, base, methods } = parse(name);
  const inherits = base === "IUnknown" ? "" : ` : ${base}`;
  if (base !== "IUnknown" && !set.has(base)) throw new Error(`${name}: base ${base} is not generated`);
  out += `\n[GeneratedComInterface(StringMarshalling = StringMarshalling.Utf16), Guid("${iid}")]\npublic partial interface ${name}${inherits}\n{\n`;
  for (const { name: mname, params } of methods) {
    const ps = params === "void" || params === "" ? [] : params.split(",").map(s => s.trim());
    let mapped;
    try { mapped = ps.map(mapParam); }
    catch (e) { mapped = null; out += `    // ${mname}: ${/** @type {Error} */ (e).message}; slot kept, do not call\n`; }
    out += mapped ? `    void ${mname}(${mapped.join(", ")});\n` : `    void ${mname}();\n`;
  }
  out += "}\n";
}
writeFileSync("src/Inlay.Launcher/WebView2/WebView2.g.cs", out);
console.log(`wrote ${wanted.length} interfaces`);
